// Builds the live site for Cloudflare: dist/ (served by the Worker) and the Worker's copy of
// the shop rules. The GitHub Pages preview keeps using the files at the project root as they are.
//   node tools/build.mjs
import { cp, mkdir, readFile, rm, writeFile, lstat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const generated = path.join(root, 'worker/src/generated');
for (const dir of [dist, generated]) {
  if (!dir.startsWith(root + path.sep)) throw new Error(`Refusing to write outside the project: ${dir}`);
  try { if ((await lstat(dir)).isSymbolicLink()) throw new Error(`Refusing a linked folder: ${dir}`); } catch (error) { if (error.code !== 'ENOENT') throw error; }
}

// The site's own files, by name: nothing else from the project reaches the public site.
const SITE_FILES = ['app.js', 'admin.js', 'data.js', 'settings.js', 'styles.css', 'admin.css', 'customization.css', 'live.js', 'live.css'];
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 12);

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });
for (const file of SITE_FILES) await cp(path.join(root, file), path.join(dist, file));
await cp(path.join(root, 'assets'), path.join(dist, 'assets'), { recursive: true });

// index.html: the page's own scripts are loaded by live.js once the published content has
// arrived, in the same order and with the same version tags.
let html = await readFile(path.join(root, 'index.html'), 'utf8');
const scripts = [];
html = html.replace(/[ \t]*<script src="([^"]+)" defer><\/script>\r?\n?/g, (_, src) => { scripts.push(src); return ''; });
if (!scripts.some((src) => src.startsWith('app.js'))) throw new Error('index.html: app.js not found');
// Pages live at deeper addresses (/devices/…, /ar/…), so every file is linked from the site root.
const fromRoot = (src) => (/^(https?:|\/|data:)/.test(src) ? src : `/${src}`);
html = html.replace(/(<link [^>]*href=")([^"]+)(")/g, (_, a, src, b) => `${a}${fromRoot(src)}${b}`);
const loader = `  <link rel="stylesheet" href="/live.css?v=${stamp}">\n  <script src="/live.js?v=${stamp}" data-scripts="${scripts.map(fromRoot).join(' ')}" defer></script>\n`;
html = html.replace('</head>', `${loader}</head>`);
await writeFile(path.join(dist, 'index.html'), html);

// robots.txt and sitemap.xml are written by the Worker from the published content.
await writeFile(path.join(dist, '_headers'), `/*
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob: https:; font-src 'self'; connect-src 'self'; object-src 'none'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: DENY
/index.html
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=604800
`);

// The Worker checks content and prices with the storefront's own rules (data.js + settings.js).
await mkdir(generated, { recursive: true });
const dataJs = await readFile(path.join(root, 'data.js'), 'utf8');
const settingsJs = await readFile(path.join(root, 'settings.js'), 'utf8');
await writeFile(path.join(generated, 'shop-rules.js'), `// Generated by tools/build.mjs from data.js and settings.js. Do not edit; edit those files.
const window = {};
${dataJs}
${settingsJs}
export const data = window.ONE_STYLE_DATA;
export const cfg = window.OneStyleConfig;
`);

console.log(JSON.stringify({ dist: path.relative(root, dist), scripts, stamp }));
